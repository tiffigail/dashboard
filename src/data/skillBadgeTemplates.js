export function getSkillBadgeTemplateById(templateId) {
  return SKILL_BADGE_TEMPLATES.find(t => t.id === templateId);
}

export function getSkillBadgeTemplates() {
  return SKILL_BADGE_TEMPLATES;
}

export function getTemplateLevels(templateId) {
  const template = getSkillBadgeTemplateById(templateId);
  return template ? template.levels : [];
}

export function getTemplateLevel(templateId, levelNumber) {
  const levels = getTemplateLevels(templateId);
  return levels.find(l => l.levelNumber === levelNumber);
}

export function getLevelDrills(templateId, levelNumber) {
  const level = getTemplateLevel(templateId, levelNumber);
  return level ? level.drills : [];
}

export function getFirstLevelNumber(templateId) {
  const template = getSkillBadgeTemplateById(templateId);
  if (!template) return 0;
  return template.levels[0]?.levelNumber ?? 0;
}
